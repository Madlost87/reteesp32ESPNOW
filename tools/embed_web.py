"""Embed the self-contained ESP32 page; no network access required."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
page=(root/'espnow_rx/web/index.html').read_text()
assert ')CENTRAL_HTML"' not in page
(root/'shared/web_page.hpp').write_text('#pragma once\n// Generated by tools/embed_web.py from espnow_rx/web/index.html\nstatic const char centralPage[] PROGMEM = R"CENTRAL_HTML('+page+')CENTRAL_HTML";\n')

radio=(root/'shared/web/radio.html').read_text()
assert ')RADIO_HTML"' not in radio
(root/'shared/radio_page.hpp').write_text('#pragma once\n// Generated from shared/web/radio.html\nstatic const char radioPage[] PROGMEM=R"RADIO_HTML('+radio+')RADIO_HTML";\n')
